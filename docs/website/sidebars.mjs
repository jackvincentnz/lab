// One sidebar per navbar tab. Each lists folders rather than pages, so a new
// page appears in its folder's tab without a sidebar change.
const folder = (dirName) => ({ type: "autogenerated", dirName });

const category = (label, dirName, extra = {}) => ({
  type: "category",
  label,
  items: [folder(dirName)],
  ...extra,
});

export default {
  overview: ["README", folder("docs/overview"), "AGENTS"],
  projects: [
    folder("projects"),
    category("Libraries", "libs"),
    category("Experiments", "learn"),
  ],
  platform: [
    folder("docs/platform"),
    category("Bazel macro reference", "docs/bazel", { collapsed: true }),
  ],
  decisions: [folder("docs/adr")],
  contribute: ["CONTRIBUTING", folder("docs/contributing")],
};

